/**
 * Product catalogue.
 *
 * Availability:
 *  - "in-stock"   → only when the client has confirmed current stock
 *  - "available"  → regularly supplied / core range
 *  - "on-request" → procured against enquiry
 *
 * Specifications only state what is defined by the product's governing
 * standard or is common market practice. Anything size-, stock- or
 * mill-specific is phrased as "on request" rather than invented.
 */

export type Availability = "in-stock" | "available" | "on-request";

export type Spec = { label: string; value: string };

